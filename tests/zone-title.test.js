import test from 'node:test';
import assert from 'node:assert/strict';
import { createZoneTracker } from '../src/zone-title.js';
import { zoneAt, ZONES } from '../src/world/zones.js';
import { SPAWN, TILE, WEST_EXTENSION, JUNGLE_ISLAND } from '../src/world/generation.js';

const at = (column, row) => zoneAt({ x: (column + WEST_EXTENSION) * TILE + 8, y: row * TILE - 11, height: 23 });
test('only The Undergrounds and The Jungle have titles', () => {
  assert.deepEqual(Object.values(ZONES).map(z => z.name), ['The Undergrounds', 'The Jungle']);
  assert.equal(zoneAt({ ...SPAWN, height: 23 }), null);
  assert.equal(at(100, 20), null);
  assert.equal(at(55, 29), null);
  assert.equal(at(-36, 188), null);
  assert.equal(at(-412, 90), null);
  assert.equal(at(60, 350), 'underground');
  assert.equal(at(JUNGLE_ISLAND.center, 8), 'jungle');
  assert.equal(at(JUNGLE_ISLAND.center, 26), 'jungle');
  assert.equal(at(900, 380), 'jungle');
  assert.equal(at(900, 430), 'jungle');
});
test('debounces entry, ignores unnamed regions, and suppresses repeat entries', () => {
  const tracker = createZoneTracker(null);
  assert.equal(tracker.update(null, 0), null);
  assert.equal(tracker.update('underground', 100), null);
  assert.equal(tracker.update(null, 400), null);
  assert.equal(tracker.update('underground', 500), null);
  assert.equal(tracker.update('underground', 1150), 'underground');
  assert.equal(tracker.update(null, 2000), null);
  assert.equal(tracker.update(null, 2650), null);
  tracker.update('underground', 3000);
  assert.equal(tracker.update('underground', 3650), null);
  assert.equal(tracker.update('underground', 35000), null);
  tracker.update(null, 36000);
  tracker.update(null, 36650);
  tracker.update('underground', 37000);
  assert.equal(tracker.update('underground', 37650), 'underground');
});
test('global cooldown waits only for a still-current region and initial load is quiet', () => {
  const tracker = createZoneTracker('jungle');
  assert.equal(tracker.update('jungle', 0), null);
  tracker.update('underground', 100);
  assert.equal(tracker.update('underground', 750), 'underground');
  tracker.update('jungle', 1000);
  assert.equal(tracker.update('jungle', 1650), null);
  tracker.update(null, 2000);
  tracker.update(null, 2650);
  assert.equal(tracker.update(null, 7000), null);
  tracker.update('jungle', 7100);
  assert.equal(tracker.update('jungle', 7750), 'jungle');
  assert.equal(tracker.update('jungle', 14000), null);
});
